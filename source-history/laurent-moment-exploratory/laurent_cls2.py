"""Minors-based classification of excess loci for the Laurent moment problem.

For a shape (monic slot + unknown slots), the truncated conditions form a linear
system A(c) q = b(c) over the parameter ring. Solvable at c  =>  every
(u+1)x(u+1) minor of [A|b] vanishes at c (u = #unknowns). Hence:
  - if the ideal generated by these minors is (1): the shape is EMPTY for all c;
  - otherwise the solvable locus is contained in V(minors); finite/small V is
    then decided pointwise with the exact engine (module_dim at each point).
Both directions use only NECESSARY conditions, so emptiness conclusions are
certificate-grade at the stated shape/box ranges.
"""
import itertools, time
import sympy as sp
from sympy import QQ
from sympy.polys.rings import ring
from lcls import sym_branch_G, sym_smul, sym_sinv

def shape_rows(m, cnames, cterms_fn, shape, E, K_extra=4):
    unknowns = sorted(k for k, v in shape.items() if v == 'u')
    R = ring(",".join(cnames), QQ)[0] if cnames else None
    gens = R.gens if cnames else ()
    cs = {nm: gens[i] for i, nm in enumerate(cnames)}
    cterms = cterms_fn(cs)
    Mneg = max(0, -min(shape.keys())); Npos = max(0, max(shape.keys()))
    K = m*E + Mneg + K_extra
    G = sym_branch_G(cterms, m, K, R)
    zero, one = R.zero, R.one
    pw = {0: [one] + [zero]*K}
    for k in range(1, Npos+1): pw[k] = sym_smul(pw[k-1], G, K, zero)
    if Mneg:
        Gi = sym_sinv(G, K, R)
        for k in range(1, Mneg+1): pw[-k] = sym_smul(pw[-(k-1)], Gi, K, zero)
    monic = next(k for k, v in shape.items() if v == 1)
    A_rows, b_col = [], []
    for e in range(1, E+1):
        row = []
        for k in unknowns:
            idx = m*e - k
            row.append(pw[k][idx] if 0 <= idx <= K else zero)
        idxm = m*e - monic
        b = -(pw[monic][idxm]) if 0 <= idxm <= K else zero
        if any(x != zero for x in row) or b != zero:
            A_rows.append(row); b_col.append(b)
    return A_rows, b_col, unknowns

def classify_shape(name, m, cnames, cterms_fn, shape, E, max_dets=14, verbose=True):
    A_rows, b_col, unknowns = shape_rows(m, cnames, cterms_fn, shape, E)
    u = len(unknowns)
    syms = [sp.Symbol(nm) for nm in cnames]
    to_expr = lambda x: sp.sympify(str(x))
    aug = [[to_expr(x) for x in row] + [to_expr(b)] for row, b in zip(A_rows, b_col)]
    nrows = len(aug)
    if nrows < u + 1:
        return ("UNDECIDED (too few rows)", None)
    dets, combos = [], []
    for s in range(nrows - u):
        combos.append(tuple(range(s, s+u+1)))
    for extra in itertools.combinations(range(min(nrows, u+4)), u+1):
        if extra not in combos: combos.append(extra)
    for rows_idx in combos[:max_dets]:
        Msub = sp.Matrix([aug[i] for i in rows_idx])
        d = Msub.det(method='berkowitz')
        d = sp.expand(d)
        if d != 0:
            dets.append(sp.factor(d))
            if len(dets) >= 2 and not syms:
                break
            if len(dets) >= 2:
                Gb = sp.groebner(dets, *syms, order='grevlex')
                if 1 in Gb.exprs or sp.S(1) in Gb.exprs or any(g == 1 for g in Gb.exprs):
                    return ("EMPTY", None)
    if not dets:
        return ("ALL (system rank-deficient identically)", None)
    if not syms:
        return ("EMPTY" if dets else "CANDIDATE", None)
    Gb = sp.groebner(dets, *syms, order='grevlex')
    if any(g == 1 for g in Gb.exprs):
        return ("EMPTY", None)
    return ("CANDIDATE V(I)", [sp.factor(g) for g in Gb.exprs])

def run_bidegree(title, m, n, cnames, cterms_fn, shapes, E):
    print(f"--- {title} ---")
    t0 = time.time(); candidates = []
    for sh in shapes:
        verdict, locus = classify_shape(title, m, cnames, cterms_fn, sh, E)
        tag = verdict if locus is None else f"{verdict}: {locus}"
        print(f"  shape {sh}: {tag}")
        if locus is not None: candidates.append((sh, locus))
    print(f"[{time.time()-t0:.1f}s]")
    return candidates

def topshapes(tops, bots, skip=()):  # monic top, unknowns below (0 and skips excluded)
    out = []
    for top in tops:
        for bot in bots:
            sh = {top: 1}
            for k in range(-bot, top):
                if k != 0 and k not in skip: sh[k] = 'u'
            out.append(sh)
    return out

def botshapes(bots):  # pure non-positive, bottom-monic
    out = []
    for bot in bots:
        sh = {-bot: 1}
        for k in range(-bot+1, 0): sh[k] = 'u'
        out.append(sh)
    return out
