#!/usr/bin/env python3
"""Exact cyclic-rank and inverse-support certificates for polynomial amplitudes.

For a polynomial phase P and polynomial amplitude A, this module compares two
independent exact calculations of the cyclic rank generated by [A(x) dx]:

1. twisted-de-Rham Krylov reduction of A, P*A, P**2*A, ... over Q(s);
2. residue-channel support of B(xi(t)), where B' = A and
   P(xi(t)) = t**deg(P).

The companion manuscript proves that these ranks agree.  Computation is used
for replay and regression evidence, not as a replacement for that proof.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import sympy as sp

from fusion_support import (
    K,
    canonical_expr,
    canonical_hash,
    coordinate_column,
    first_dependence,
    next_inverse_coefficient,
    normalise_phase,
    parse_polynomial,
    power_coefficient,
    require,
    x,
)


def parse_amplitude(text: str) -> sp.Poly:
    require(isinstance(text, str), "amplitude must be a string")
    expr = sp.expand(sp.sympify(text, locals={"x": x}))
    require(expr.free_symbols <= {x}, "amplitude must lie in Q[x]")
    try:
        return sp.Poly(expr, x, domain=sp.QQ)
    except (sp.PolynomialError, sp.CoercionFailed) as error:
        raise RuntimeError("amplitude must lie in Q[x]") from error


def normalise_amplitude(amplitude: sp.Poly, source_shift: sp.Rational) -> sp.Poly:
    """Transport A(x_old) dx_old under x_old = x_new - source_shift."""

    expr = sp.expand(amplitude.as_expr().subs(x, x - source_shift))
    return sp.Poly(expr, x, domain=sp.QQ)


def primitive(amplitude: sp.Poly) -> sp.Poly:
    expr = sp.integrate(amplitude.as_expr(), x)
    result = sp.Poly(sp.expand(expr), x, domain=sp.QQ)
    require(result.diff() == amplitude, "failed to construct amplitude primitive")
    return result


def seed_krylov_matrix(phase: sp.Poly, amplitude: sp.Poly) -> sp.Matrix:
    """Columns are [A dx], [P A dx], ... in the twisted quotient."""

    ambient_rank = phase.degree() - 1
    phase_k = sp.Poly(phase.as_expr(), x, domain=K)
    iterate = sp.Poly(amplitude.as_expr(), x, domain=K)
    columns: list[sp.Matrix] = []
    for _ in range(ambient_rank):
        columns.append(coordinate_column(iterate, phase))
        iterate *= phase_k
    return sp.Matrix.hstack(*columns)


def amplitude_cyclic_rank_certificate(
    phase: sp.Poly, amplitude: sp.Poly
) -> tuple[int, dict[str, Any]]:
    matrix = seed_krylov_matrix(phase, amplitude)
    rank = first_dependence(matrix)
    payload = [canonical_expr(value) for value in matrix]
    certificate: dict[str, Any] = {
        "ambient_rank": phase.degree() - 1,
        "cyclic_rank": rank,
        "matrix_shape": list(matrix.shape),
        "matrix_sha256": canonical_hash(payload),
    }
    if rank == 0:
        require(all(value == 0 for value in matrix[:, 0]), "rank-zero seed is nonzero")
        certificate["rank_zero_witness"] = "the reduced seed column is identically zero"
        return rank, certificate

    basis = matrix[:, :rank]
    _rref, pivot_rows_tuple = basis.T.rref()
    pivot_rows = list(pivot_rows_tuple)
    require(len(pivot_rows) == rank, "failed to select an amplitude rank minor")
    minor = sp.factor(basis.extract(pivot_rows, range(rank)).det())
    require(minor != 0, "amplitude independence minor vanished")
    numerator, denominator = sp.fraction(sp.cancel(minor))
    certificate["independence"] = {
        "pivot_rows_zero_based": pivot_rows,
        "minor_numerator": canonical_expr(numerator),
        "minor_denominator": canonical_expr(denominator),
        "minor_is_nonzero": True,
    }

    if rank < matrix.cols:
        square = basis.extract(pivot_rows, range(rank))
        target = matrix[:, rank]
        coefficients = square.inv() * target.extract(pivot_rows, [0])
        residual = basis * coefficients - target
        require(all(sp.cancel(value) == 0 for value in residual), "amplitude dependence failed")
        certificate["first_dependence"] = {
            "dependent_iterate": rank,
            "orientation": "[P^q A dx] = sum_i coefficient[i] [P^i A dx]",
            "coefficients_low_to_high": [canonical_expr(value) for value in coefficients],
            "residual_is_zero": True,
        }
    else:
        certificate["first_dependence"] = None
    return rank, certificate


def composition_coefficient(
    primitive_poly: sp.Poly,
    inverse_coefficients: list[sp.Rational],
    t_exponent: int,
) -> sp.Rational:
    """Return [t^t_exponent] B(t F(1/t)) exactly."""

    total = sp.Rational(0)
    for degree in range(primitive_poly.degree() + 1):
        coefficient = sp.Rational(primitive_poly.nth(degree))
        if coefficient == 0:
            continue
        series_degree = degree - t_exponent
        if series_degree < 0:
            continue
        total += coefficient * power_coefficient(
            inverse_coefficients, degree, series_degree
        )
    return sp.factor(total)


def amplitude_support_certificate(
    phase: sp.Poly,
    primitive_poly: sp.Poly,
    cyclic_rank: int,
    max_terms: int = 10000,
) -> dict[str, Any]:
    """Expand B(xi(t)) until every exact non-trace channel is witnessed."""

    if primitive_poly.is_zero:
        require(cyclic_rank == 0, "zero primitive must have zero cyclic rank")
        return {
            "support": [],
            "support_size": 0,
            "terms_computed": 0,
            "witnesses": {},
            "nonzero_terms_through_stopping_order": [],
            "stopping_rule": "zero primitive",
        }

    d = phase.degree()
    top_degree = primitive_poly.degree()
    inverse_coefficients = [sp.Rational(1)]
    support: set[int] = set()
    witnesses: dict[int, dict[str, Any]] = {}
    nonzero_terms: list[dict[str, Any]] = []

    for order in range(0, max_terms + 1):
        if order:
            inverse_coefficients.append(
                sp.Rational(next_inverse_coefficient(phase, inverse_coefficients, order))
            )
        exponent = top_degree - order
        coefficient = composition_coefficient(
            primitive_poly, inverse_coefficients, exponent
        )
        if coefficient != 0:
            residue = exponent % d
            nonzero_terms.append(
                {
                    "t_exponent": exponent,
                    "coefficient": canonical_expr(coefficient),
                    "residue_mod_degree": residue,
                }
            )
            if residue != 0:
                support.add(residue)
                witnesses.setdefault(
                    residue,
                    {
                        "t_exponent": exponent,
                        "coefficient": canonical_expr(coefficient),
                        "series_order": order,
                    },
                )
        if len(support) == cyclic_rank:
            return {
                "support": sorted(support),
                "support_size": len(support),
                "terms_computed": order,
                "witnesses": {
                    str(key): witnesses[key] for key in sorted(witnesses)
                },
                "nonzero_terms_through_stopping_order": nonzero_terms,
                "stopping_rule": "support_size equals exact amplitude cyclic rank",
            }

    raise RuntimeError(
        f"failed to witness {cyclic_rank} amplitude channels in {max_terms} terms"
    )


def polynomial_in_phase(
    primitive_poly: sp.Poly, phase: sp.Poly
) -> tuple[bool, sp.Poly | None]:
    """Decide whether B belongs to Q[P] and return C with B=C(P)."""

    if primitive_poly.is_zero:
        return True, sp.Poly(0, x, domain=sp.QQ)
    d = phase.degree()
    remainder = sp.Poly(primitive_poly.as_expr(), x, domain=sp.QQ)
    y = sp.Symbol("y")
    outer = sp.Poly(0, y, domain=sp.QQ)
    while not remainder.is_zero and remainder.degree() >= d:
        degree = remainder.degree()
        if degree % d:
            return False, None
        power = degree // d
        coefficient = sp.Rational(remainder.LC())
        outer += sp.Poly(coefficient * y**power, y, domain=sp.QQ)
        remainder = sp.Poly(
            sp.expand(remainder.as_expr() - coefficient * phase.as_expr() ** power),
            x,
            domain=sp.QQ,
        )
    if not remainder.is_zero:
        if remainder.degree() > 0:
            return False, None
        outer += sp.Poly(sp.Rational(remainder.nth(0)), y, domain=sp.QQ)
    recomposed = sp.expand(outer.as_expr().subs(y, phase.as_expr()))
    require(
        sp.expand(recomposed - primitive_poly.as_expr()) == 0,
        "phase-composition reconstruction failed",
    )
    return True, outer


def analyse_amplitude(phase_text: str, amplitude_text: str) -> dict[str, Any]:
    original_phase = parse_polynomial(phase_text)
    original_amplitude = parse_amplitude(amplitude_text)
    normalisation = normalise_phase(original_phase)
    phase = normalisation.normalised
    amplitude = normalise_amplitude(original_amplitude, normalisation.source_shift)
    primitive_poly = primitive(amplitude)

    rank, rank_certificate = amplitude_cyclic_rank_certificate(phase, amplitude)
    support_certificate = amplitude_support_certificate(phase, primitive_poly, rank)
    in_phase, outer = polynomial_in_phase(primitive_poly, phase)
    support = support_certificate["support"]
    require(rank == len(support), "amplitude support/rank mismatch")
    require((rank == 0) == in_phase, "rank-zero/factor-through-P mismatch")

    result: dict[str, Any] = {
        "schema": "cyclicity-amplitude-support-certificate-v1",
        "status": "pass",
        "input": {"phase": phase_text, "amplitude": amplitude_text},
        "normalisation": normalisation.as_dict(),
        "normalised_amplitude": sp.sstr(amplitude.as_expr()),
        "normalised_primitive_B": sp.sstr(primitive_poly.as_expr()),
        "degree": phase.degree(),
        "theorem_identity": {
            "twisted_amplitude_cyclic_rank": rank,
            "primitive_inverse_support_size": len(support),
            "reduced_B_root_span_dimension": len(support),
            "all_equal": rank == len(support),
        },
        "twisted_krylov": rank_certificate,
        "primitive_inverse_at_infinity": support_certificate,
        "universal_vanishing": {
            "rank_zero": rank == 0,
            "primitive_factors_through_phase": in_phase,
            "outer_polynomial": None if outer is None else sp.sstr(outer.as_expr()),
        },
        "claim_boundary": {
            "proved_by_successor_manuscript": [
                "q(P,A dx)=|Sigma(P;B)| for B'=A",
                "rank zero iff B belongs to C[P]",
                "the zero-cycle Fourier annihilation criterion",
            ],
            "not_asserted": [
                "that a chosen non-generic contour detects every active channel",
                "a multivariate amplitude theorem",
                "a Laurent two-pole cyclic-rank theorem",
            ],
        },
    }
    result["certificate_sha256"] = canonical_hash(result)
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", required=True, help="trusted Q[x] expression")
    parser.add_argument("--amplitude", required=True, help="trusted Q[x] expression")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    result = analyse_amplitude(args.phase, args.amplitude)
    encoded = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(encoded, encoding="utf-8")
    else:
        print(encoded, end="")


if __name__ == "__main__":
    main()
